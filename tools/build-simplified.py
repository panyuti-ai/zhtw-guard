"""Regenerate plugins/zhtw-guard/lib/simplified-chars.js from OpenCC.

Usage:
  python tools/build-simplified.py STCharacters.txt TSCharacters.txt TWVariants.txt

Download the three files from
https://github.com/BYVoid/OpenCC/tree/master/data/dictionary (Apache-2.0).

A character counts as Simplified-only when OpenCC maps it to a different
Traditional character and it never appears as a Traditional character
itself. That keeps characters such as 后, 里 and 么, which are also valid
in Traditional text, out of the list.

OpenCC's Traditional forms are the older orthodox ones (羣, 祕). Taiwan's
standard forms (群) come from TWVariants.txt and are removed too, as is
TAIWAN_IN_USE: characters OpenCC treats as Simplified that Taiwan's own
official term list (NAER 電子計算機名詞, 2026-08-21) uses often (秘: 21 entries), and 霉,
common in Taiwan writing (倒霉, 發霉; author's judgment).
"""
import json
import pathlib
import sys

TAIWAN_IN_USE = {"秘", "霉"}

OUT = pathlib.Path(__file__).resolve().parent.parent / "plugins/zhtw-guard/lib/simplified-chars.js"


def load(path):
    table = {}
    for line in open(path, encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        key, values = line.rstrip("\n").split("\t")
        table[key] = values.split(" ")
    return table


def load_all(path):
    chars = set()
    for line in open(path, encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        key, values = line.rstrip("\n").split("\t")
        chars.update(values.split(" "))
    return chars


def main(st_path, ts_path, tw_path):
    st = load(st_path)
    ts = load(ts_path)
    tw = load_all(tw_path)
    traditional = set(ts) | {c for values in st.values() for c in values} | tw | TAIWAN_IN_USE
    pairs = [
        (k, v[0])
        for k, v in st.items()
        if len(k) == 1 and k not in v and k not in traditional
    ]
    OUT.write_text(
        "// Generated by tools/build-simplified.py from OpenCC data/dictionary/STCharacters.txt\n"
        "// TSCharacters.txt and TWVariants.txt (Apache-2.0, see NOTICE). Do not edit by hand.\n"
        "// Each entry: a character used only in Simplified Chinese -> its first Traditional form.\n"
        "'use strict';\nmodule.exports = new Map("
        + json.dumps(pairs, ensure_ascii=False)
        + ");\n",
        encoding="utf-8",
    )
    print(f"{len(pairs)} characters -> {OUT}")


if __name__ == "__main__":
    main(*sys.argv[1:4])
