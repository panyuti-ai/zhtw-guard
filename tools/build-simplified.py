"""Regenerate plugins/zhtw-guard/lib/simplified-chars.js from OpenCC.

Usage:
  python tools/build-simplified.py STCharacters.txt TSCharacters.txt

Download both files from
https://github.com/BYVoid/OpenCC/tree/master/data/dictionary (Apache-2.0).

A character counts as Simplified-only when OpenCC maps it to a different
Traditional character and it never appears as a Traditional character
itself. That keeps characters such as 后, 里 and 么, which are also valid
in Traditional text, out of the list.
"""
import json
import pathlib
import sys

OUT = pathlib.Path(__file__).resolve().parent.parent / "plugins/zhtw-guard/lib/simplified-chars.js"


def load(path):
    table = {}
    for line in open(path, encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        key, values = line.rstrip("\n").split("\t")
        table[key] = values.split(" ")
    return table


def main(st_path, ts_path):
    st = load(st_path)
    ts = load(ts_path)
    traditional = set(ts) | {c for values in st.values() for c in values}
    pairs = [
        (k, v[0])
        for k, v in st.items()
        if len(k) == 1 and k not in v and k not in traditional
    ]
    OUT.write_text(
        "// Generated by tools/build-simplified.py from OpenCC data/dictionary/STCharacters.txt\n"
        "// and TSCharacters.txt (Apache-2.0, see NOTICE). Do not edit by hand.\n"
        "// Each entry: a character used only in Simplified Chinese -> its first Traditional form.\n"
        "'use strict';\nmodule.exports = new Map("
        + json.dumps(pairs, ensure_ascii=False)
        + ");\n",
        encoding="utf-8",
    )
    print(f"{len(pairs)} characters -> {OUT}")


if __name__ == "__main__":
    main(*sys.argv[1:3])
